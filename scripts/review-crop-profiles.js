async page => {
  const check = (condition, message) => { if (!condition) throw new Error(message) }
  const button = (name, root = page) => root.getByRole('button', {name, exact: true})
  const combo = name => page.getByRole('combobox', {name, exact: true})
  const details = page.getByRole('dialog', {name: 'Anbaudaten', exact: true})
  const editor = page.getByRole('dialog', {name: 'Kulturprofil bearbeiten', exact: true})
  const profile = details.locator('.crop-profile')
  const library = details.locator('.variety-library').filter({hasText: 'Sortenbibliothek'})
  const field = (name, root = details) => root.getByLabel(name, {exact: true})
  const value = name => field(name).inputValue()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(10_000)
  await page.setViewportSize({width: 1440, height: 960})
  await page.goto('http://127.0.0.1:5173/')

  const title = 'Bagua Kulturprofil ' + Date.now()
  await page.locator('#garden').selectOption('bagua')
  await page.getByText('Vorlagen', {exact: true}).click()
  await button('Sichtbares Bagua-Netz laden').click()
  await button('Fläche auswählen').click()
  const point = await page.locator('#map').evaluate(map => {
    const position = new DOMPoint(475, 270).matrixTransform(map.getScreenCTM())
    return [position.x, position.y]
  })
  await page.mouse.click(...point)
  const id = await page.locator('#regions legend').textContent()
  await page.getByLabel('Objekttyp im Bestand').selectOption('bed')
  await page.getByLabel('Gartenname').fill(title)
  await button('Beetplan').click()
  await combo('Grundfläche').selectOption(id)
  await page.getByLabel('Unterteilungen', {exact: true}).fill('7')
  await button('Unterteilung übernehmen').click()
  const strip = id + ':strip:3'
  await combo('Streifen').selectOption(strip)
  await combo('Kultur').selectOption('Möhre')
  await button('Belegung speichern').click()
  await page.getByText('Gespeichert · Möhre', {exact: true}).waitFor()
  const savedGarden = () => page.evaluate(async name => {
    const {listProjects} = await import('/src/integrated-storage.js')
    return (await listProjects()).find(project => project.name === name)
  }, title)
  const before = await savedGarden()
  await button('Anbaudaten').click()
  await profile.locator('summary').click()
  await button('Profil bearbeiten', profile).click()

  const row = 'Reihenabstand (cm)'
  const distance = 'Abstand in der Reihe (cm)'
  const minimum = 'Kulturdauer mindestens (Tage)'
  const maximum = 'Kulturdauer höchstens (Tage)'
  const source = 'Gartenversuch Möhre 2026'
  const sourceUrl = 'https://example.org/anbau-notizen'
  const edit = (name, text) => field(name, editor).fill(text)
  await edit('Quelle des Kulturprofils', '')
  await edit(row, '35')
  await button('Kulturprofil speichern', editor).click()
  check(await field('Quelle des Kulturprofils', editor).evaluate(input => input.validity.valueMissing),
    'Kulturprofil ohne Quelle wurde nicht abgewiesen')
  await edit('Quelle des Kulturprofils', source)
  await edit('Quellenlink (optional)', sourceUrl)
  await edit(row, '0.5')
  await button('Kulturprofil speichern', editor).click()
  check(await field(row, editor).evaluate(input => input.validity.rangeUnderflow), 'Ungültiger Abstand wurde akzeptiert')
  await edit(row, '35')
  await edit(distance, '8')
  await edit(minimum, '75')
  await edit(maximum, '')
  await button('Kulturprofil speichern', editor).click()
  await profile.getByText('Kulturprofil gespeichert.', {exact: true}).waitFor()
  check(await value(row) === '', 'Profil speichern änderte das Anbauformular')
  check(await profile.getByRole('link', {name: source, exact: true}).getAttribute('href') === sourceUrl,
    'Quellenlink wurde nicht erhalten')

  await field(row).fill('40')
  await field(distance).fill('12')
  await field(maximum).fill('70')
  await field('Aussaatdatum').fill('2028-04-01')
  const days = profile.getByRole('checkbox', {name: 'Kulturdauer · ab 75 Tagen', exact: true})
  const spacing = profile.getByRole('checkbox', {name: 'Reihenabstand · 35 cm', exact: true})
  const inRow = profile.getByRole('checkbox', {name: 'Abstand in der Reihe · 8 cm', exact: true})
  const adopt = button('Ausgewählte Richtwerte übernehmen', profile)
  check(await adopt.isDisabled(), 'Richtwerte waren vorausgewählt')
  await days.check()
  await adopt.click()
  await profile.getByText(/Mindest- und Höchstdauer widersprechen sich/).waitFor()
  check(await value(maximum) === '70' && await value(minimum) === '', 'Widersprüchliche Dauer änderte das Formular')
  await days.uncheck()
  await spacing.check()
  await inRow.check()
  let confirmation
  page.once('dialog', prompt => { confirmation = prompt.message(); return prompt.dismiss() })
  await adopt.click()
  check(confirmation?.includes('abweichende Angaben') && await value(row) === '40', 'Abbruch änderte Richtwerte')
  page.once('dialog', prompt => prompt.accept())
  await adopt.click()
  check(await value(row) === '35' && await value(distance) === '8' && await value(minimum) === '' &&
    await value(maximum) === '70' && await value('Aussaatdatum') === '2028-04-01', 'Gezielte Übernahme änderte andere Felder')

  await field(row).fill('37')
  const variety = 'Bagua Gartensorte ' + Date.now()
  await field('Sorte').fill(variety)
  await library.locator('summary').click()
  await button('Eigene Sorte speichern', library).click()
  await library.getByText('Eigene Sorte gespeichert.', {exact: true}).waitFor()
  await library.getByText('Reihenabstand · 35 cm · in der Sorte abweichend', {exact: true}).waitFor()
  check(JSON.stringify(await savedGarden()) === JSON.stringify(before), 'Bibliothek veränderte den Gartenstand')

  await button('Profil bearbeiten', profile).click()
  await edit('Quelle des Kulturprofils', 'Gartenversuch Möhre 2027')
  await edit(row, '45')
  await edit(distance, '10')
  await button('Kulturprofil speichern', editor).click()
  await profile.getByText('Kulturprofil gespeichert.', {exact: true}).waitFor()
  await button('Abbrechen', details).click()
  await button('Garten schließen').click()
  await button(title).click()
  await combo('Grundfläche').selectOption(id)
  await combo('Streifen').selectOption(strip)
  await button('Anbaudaten').click()
  await library.locator('summary').click()
  await library.getByRole('combobox', {name: 'Sorte aus Bibliothek'}).selectOption({label: variety + ' · eigene Sorte'})
  await library.getByText('Reihenabstand · 37 cm', {exact: true}).waitFor()
  await library.getByRole('link', {name: source, exact: true}).waitFor()
  check(await value(row) === '', 'Eigene Sorte wurde automatisch am Beet übernommen')
  await button('Richtwerte übernehmen', library).click()
  check(await value(row) === '37' && await value(distance) === '8', 'Profiländerung überschrieb die gespeicherte Sortenkopie')
  await details.locator('.variety-profile').filter({hasText: 'Beibehaltene Richtwerte · Möhre'})
    .getByRole('link', {name: source, exact: true}).waitFor()
  await button('Anbaudaten speichern', details).click()
  await page.getByText('Anbaudaten gespeichert.', {exact: true}).waitFor()
  const saved = await savedGarden()
  check(saved.revision === before.revision + 1 && saved.planning.plantings[strip].rowSpacingCm === 37,
    'Anbaudaten wurden nicht in einer eigenen Revision gespeichert')

  await button('Anbaudaten').click()
  await profile.locator('summary').click()
  await profile.getByRole('checkbox', {name: 'Reihenabstand · 45 cm', exact: true}).waitFor()
  await details.evaluate(dialog => { dialog.scrollTop = 0 })
  check(errors.length === 0, errors.join(' / '))
  return {strip, variety, before: before.revision, saved: saved.revision, cropRowSpacing: 45, varietyRowSpacing: 37, source}
}
