async page => {
  const check = (value, message) => { if (!value) throw new Error(message) }
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({width: 1440, height: 980})
  await page.goto(new URL('/experiments/way-guided/', page.url()).href)
  const button = name => page.getByRole('button', {name, exact: true})
  const map = page.locator('#map')
  const view = () => map.getAttribute('viewBox')
  const standard = page.getByLabel('Standardbreite (cm)')
  await page.waitForFunction(() => document.querySelector('#garden').options.length === 3)
  await page.evaluate(() => {
    const create = URL.createObjectURL.bind(URL)
    URL.createObjectURL = blob => {
      window.auditDownload = blob.text().then(JSON.parse)
      return create(blob)
    }
  })
  const data = async () => {
    const download = page.waitForEvent('download')
    await button('Versuchsdaten speichern').click()
    check((await download).suggestedFilename() === 'wegversuch.json', 'JSON download missing')
    return page.evaluate(() => window.auditDownload)
  }
  const client = point => map.evaluate((element, [x, y]) => {
    const screen = new DOMPoint(x, y).matrixTransform(element.getScreenCTM())
    return [screen.x, screen.y]
  }, point)
  const pixel = async point => page.mouse.click(...await client(point))
  const draw = async (name, points) => {
    await button(name).click()
    for (const point of points) await pixel(point)
    await button('Zeichnung abschließen').click()
  }
  const set = async (input, value) => { await input.fill(value); await input.press('Tab') }
  const levels = output => output.result.lines.map(line => line.sections.map(section => section.widthMetres))
  const compare = (actual, expected, message) => check(JSON.stringify(actual) === JSON.stringify(expected), message)
  const reset = async () => {
    await page.getByText('Vorlagen', {exact: true}).click()
    await button('Neu beginnen').click()
  }
  const drag = async (from, delta, button = 'left') => {
    await page.mouse.move(...from)
    await page.mouse.down({button})
    await page.mouse.move(from[0] + delta[0], from[1] + delta[1], {steps: 5})
    await page.mouse.up({button})
  }

  const fresh = await data()
  compare([fresh.boundary, fresh.axes, fresh.regions, fresh.result], [[], [], [], null], 'Opening the editor loaded a template')
  await draw('Wegachse zeichnen', [[230,310],[420,310]])
  await button('Weggeometrie nachbearbeiten').click()
  await pixel([340,310])
  await set(page.getByLabel('Wegbreite (cm)', {exact: true}), '120')
  check((await data()).axes[0].width === 1.2, 'Axes should be editable before drawing a plot')
  await button('Achse entfernen').click()
  check(!(await data()).axes.length, 'Removing an axis required a plot')
  await page.getByText('Vorlagen', {exact: true}).click()
  await button('Frühere Achsen laden').click()
  check((await data()).axes.length === 1, 'Explicit template did not load its original axis')

  const initial = await view()
  const original = await data()
  const anchor = (await client([390,405])).map(Math.round)
  const position = () => map.evaluate((element, [x,y]) =>
    new DOMPoint(x,y).matrixTransform(element.getScreenCTM().inverse()).toJSON(), anchor)
  const beforeWheel = await position()
  await page.mouse.move(...anchor)
  await page.mouse.wheel(0, -220)
  await page.waitForFunction(value => document.querySelector('#map').getAttribute('viewBox') !== value, initial)
  const afterWheel = await position()
  check(Math.hypot(beforeWheel.x - afterWheel.x, beforeWheel.y - afterWheel.y) < 0.01, 'Wheel moved anchor')
  const zoomed = await view()
  await button('Vergrößern').click()
  check(await view() !== zoomed, 'Zoom-in button did not change viewport')
  await button('Verkleinern').click()
  const beforeDrag = await view()
  await button('Verschieben').click()
  const box = await map.boundingBox()
  await drag([box.x + 270, box.y + 205], [60, 35])
  check(await view() !== beforeDrag, 'Pan did not move viewport')
  await button('Verschieben').click()
  await button('Grundstück einpassen').click()
  compare(await view(), initial, 'Fit did not restore the view')
  compare(await data(), original, 'Navigation changed exported geometry')
  const wide = await map.boundingBox()
  const sidebar = await page.getByRole('complementary').boundingBox()
  check(wide.width > 2 * sidebar.width, 'Map does not dominate desktop layout')

  await reset()
  await draw('Grenze zeichnen', [[150,150],[500,150],[500,500],[150,500]])
  await draw('Wegachse zeichnen', [[230,310],[420,310]])
  const extended = await data()
  check(extended.result.lines[0].extensions.length === 2 && extended.regions.length === 2, 'Open axis did not partition at the boundary')
  await button('Weggeometrie nachbearbeiten').click()
  await pixel([340,310])
  await button('Verlängerung am Anfang korrigieren').click()
  await pixel([210,185])
  const corrected = await data()
  compare(corrected.axes, extended.axes, 'Correcting an extension edited the original axis')
  compare(corrected.result.paths, extended.result.paths, 'Correcting a separator changed real way surfaces')
  compare(corrected.net.paths, extended.net.paths, 'Correcting a separator changed usable way surfaces')
  check(corrected.result.lines[0].extensions[0].corrected && corrected.regions.length === 2, 'Corrected extension did not partition')
  await button('Verlängerung am Anfang zurücksetzen').click()
  compare((await data()).result, extended.result, 'Reset did not restore the automatic partition')

  const plot = [[150,150],[480,150],[480,480],[150,480]]
  const arms = [[[315,263],[315,200]],[[367,315],[430,315]],[[315,367],[315,430]],[[263,315],[200,315]]]
  for (const hasCentre of [false, true]) {
    await reset()
    await draw('Grenze zeichnen', plot)
    if (hasCentre) await draw('Wegachse zeichnen', [[263,263],[367,263],[367,367],[263,367],[263,263]])
    for (const arm of arms) await draw('Wegachse zeichnen', arm)
    const partition = await data()
    check(partition.regions.length === (hasCentre ? 5 : 4), 'Four-arm partition has the wrong number of faces')
    if (hasCentre) {
      check(await page.locator('#overlays polyline[stroke-dasharray]').count() === 4, 'Expected four visible virtual separators')
    }
  }

  await reset()
  await set(standard, '70')
  await draw('Grenze zeichnen', [[150,150],[500,150],[500,500],[150,500]])
  await button('Wegachse zeichnen').click()
  await pixel([145,310])
  const activeView = await view()
  await drag(await client([320,290]), [22, 20], 'middle')
  check(await view() !== activeView, 'Middle-button pan failed during drawing')
  await pixel([340,310])
  await pixel([505,310])
  await button('Zeichnung abschließen').click()
  await draw('Wegachse zeichnen', [[340,145],[340,310],[340,505]])
  const crossing = await data()
  check(crossing.axes.every(axis => axis.points.length === 3), 'Navigation inserted a drawing point')
  compare(crossing.axes[0].points[1], crossing.axes[1].points[1], 'Junction did not snap')
  check(crossing.result.paths.length === 1 && crossing.regions.length === 4, 'Cross topology changed')
  compare(levels(crossing), [[0.7,0.7],[0.7,0.7]], 'Incorrect standard widths')

  await button('Fläche auswählen').click()
  await pixel([230,230])
  const region = page.locator('#regions fieldset').first()
  const id = await region.locator('legend').textContent()
  await region.getByLabel('Objekttyp im Bestand').selectOption('bed')
  check(await page.locator('#regions input').count() === 0, 'Planting input exposed in inventory')
  await set(standard, '100')
  const standardChanged = await data()
  compare(levels(standardChanged), [[1,1],[1,1]], 'Standard change did not reach existing ways')
  check(JSON.stringify(crossing.result.paths) !== JSON.stringify(standardChanged.result.paths), 'Standard did not change polygon')
  check(!await page.locator('#paths').isVisible(), 'Width detail shown during drawing')

  await button('Weggeometrie nachbearbeiten').click()
  check(!await page.locator('#paths').isVisible(), 'Width detail shown without selection')
  await pixel([235,310])
  const pathWidth = page.getByLabel('Wegbreite (cm)', {exact: true})
  const segmentWidth = page.getByLabel('Abschnittsbreite (cm)', {exact: true})
  await set(pathWidth, '120')
  await set(segmentWidth, '150')
  await set(standard, '90')
  compare(levels(await data()), [[1.5,1.2],[0.9,0.9]], 'Section > path > standard precedence failed')
  await button('Punkt versetzen').click()
  await pixel([340,310])
  await pixel([345,317])
  const moved = await data()
  compare(moved.axes[0].points[1], moved.axes[1].points[1], 'Shared node split on move')
  check(moved.axes[0].points[1][1] > 315, 'Node did not move')
  check(moved.regions.find(r => r.id === id)?.kind === 'bed', 'Inventory classification lost its region')
  await button('Punkt einsetzen').click()
  await pixel([242,314])
  compare(levels(await data()), [[1.5,1.5,1.2],[0.9,0.9]], 'Section split lost override')
  await button('Punkt entfernen').click()
  await pixel([242,314])
  compare(levels(await data()), [[1.5,1.2],[0.9,0.9]], 'Removing point did not preserve compatible width')
  await button('Weg auswählen').click()
  await pixel([225,313])
  await set(segmentWidth, '')
  compare(levels(await data()), [[1.2,1.2],[0.9,0.9]], 'Clearing section did not restore inherited width')
  await draw('Objektumriss zeichnen', [[185,185],[250,185],[245,245],[185,230]])
  check((await data()).outlines.length === 1, 'Manual polygon missing')
  check(await page.locator('#regions input').count() === 0, 'Manual inventory outline exposes a planting input')

  await page.evaluate(() => { window.confirm = () => false })
  await page.locator('#garden').selectOption('bagua')
  check(await page.locator('#garden').inputValue() === 'tandel' && (await data()).axes.length === 2,
    'Dismissing a garden switch discarded work')
  await page.evaluate(() => { window.confirm = () => true })
  await page.locator('#garden').selectOption('bagua')
  const changedGarden = await data()
  compare([changedGarden.boundary, changedGarden.axes, changedGarden.regions, changedGarden.result], [[], [], [], null],
    'Changing the background loaded a template')
  await page.getByText('Vorlagen', {exact: true}).click()
  await button('Sichtbares Bagua-Netz laden').click()
  await page.waitForFunction(() => document.querySelector('#stats').textContent.startsWith('1 verbundene Wegfläche'))
  if (await page.locator('#land').getAttribute('open') !== null) {
    await page.getByText('Flächen und Bestand', {exact: true}).click()
  }
  await button('Weggeometrie nachbearbeiten').click()
  await pixel([446,205])
  check(await page.locator('#paths').isVisible(), 'No settings for selected Bagua way')
  await page.setViewportSize({width: 390, height: 740})
  await button('Grundstück einpassen').click()
  const mobileMap = await map.boundingBox()
  await page.getByRole('complementary').evaluate(el => { el.scrollTop = el.scrollHeight })
  const scrolled = await map.boundingBox()
  check(mobileMap.height > 290 && mobileMap.width < 390, 'Mobile map too small or overflows')
  compare(scrolled, mobileMap, 'Settings scroll moved the mobile map')
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile horizontal overflow')
  check(errors.length === 0, errors.join('\n'))
  return {zoomAnchorStable: true, navigationPreservedExport: true, crossing: '1 Wegfläche, 4 Restflächen',
    overridesMetres: [1.5, 1.2, 0.9], inventory: id + ' / Beet', mobileMap: mobileMap.height}
}
